import { execSync } from 'node:child_process';
import * as S from '../src/sim.js';
const w = S.migrate(JSON.parse(execSync('git show origin/world-data:state.json', { maxBuffer: 64 << 20 }).toString()));
S.advanceTo(w, Math.max(w.t, S.tickAt(w, Date.now())));
const s = S.summary(w);
console.log(JSON.stringify({ year: s.year, season: s.season, pop: s.pop, adults: s.adults, children: s.children, food: s.food, timber: s.timber, houses: s.houses, fields: s.fields, births: s.births, deaths: s.deaths }));
console.log('techs:', w.techs.join(', '));
console.log('\nyearly:'); for (const y of w.hist.yearly.slice(-12)) console.log(' ', JSON.stringify(y));
console.log('\nchronicle:'); for (const e of w.chronicle.slice(-30)) console.log(' ', e.s, e.text);
console.log('\nlog:'); for (const e of w.log.slice(-30)) console.log(' ', e.s, `[${e.k}]`, e.text);
