import { execSync } from 'node:child_process';
import * as S from '../src/sim.js';
const years = +(process.argv[2] || 10);
const w = S.migrate(JSON.parse(execSync('git show origin/world-data:state.json', { maxBuffer: 64 << 20 }).toString()));
const y0 = S.clock(w.t).year;
const t0 = Date.now();
S.advanceTo(w, w.t + years * S.TICKS_PER_YEAR);
console.log('ms/yr', Math.round((Date.now() - t0) / years), 'pop', w.people.length, 'from year', y0);
const B = w.bear;
console.log(JSON.stringify(B && { ...B, cur: B.cur && B.cur.nm }));
console.log('hives', w.bees && w.bees.h.map((h) => `${h.a ? 'live' : 'dead'}:${Math.round(h.c)}`).join(' '), 'honey kept', w.bees && w.bees.hy, 'cheese', w.cheese && w.cheese.c);
for (const e of [...w.chronicle, ...w.log].filter((e) => /bear|Old Brown|Honey-Paw|Grey Sow|Broad-Back|Notch-Ear/.test(e.text)).slice(-14)) console.log(' ', e.s, e.text);
