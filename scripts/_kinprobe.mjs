// Probe the Families tree: every known islander must appear exactly once as a node.
import * as S from '../src/sim.js';
import { readFileSync } from 'node:fs';
const src = readFileSync(new URL('../src/render.js', import.meta.url), 'utf8');
const body = src.slice(src.indexOf('function kinFolk()'), src.indexOf('function drawFamilies('));
const years = +(process.argv[2] || 60), seed = +(process.argv[3] || 20261114);
const w = S.genesis(seed, 0);
S.advanceTo(w, years * S.TICKS_PER_YEAR);
const kinFolk = new Function('w', 'S', body + '\nreturn kinFolk;')(w, S);
const { all, under, roots, mates } = kinFolk();
const seen = new Map();
let deep = 0;
const walk = (id, d) => { seen.set(id, (seen.get(id) || 0) + 1); deep = Math.max(deep, d + 1); for (const c of under.get(id) || []) walk(c, d + 1); };
for (const r of roots) walk(r, 0);
const inline = new Set();
for (const id of seen.keys()) for (const m of mates.get(id) || []) inline.add(m);
const missing = [...all.keys()].filter((id) => !seen.has(id) && !inline.has(id));
const twice = [...seen].filter(([, n]) => n > 1);
console.log(`Y${years}: known ${all.size}, living ${w.people.length}, roll ${w.roll.length}, graves ${w.graves.length}, roots ${roots.length}, generations ${deep}`);
console.log(`missing ${missing.length}, shown twice ${twice.length}, nodes ${seen.size}, inline-only ${[...inline].filter((i) => !seen.has(i)).length}`);
const draw = src.slice(src.indexOf('function drawFamilies('), src.indexOf('function showFamilies('));
const els = {};
const $ = (id) => (els[id] ||= { textContent: '', innerHTML: '', classList: { add() {} }, scrollIntoView() {} });
const esc = (s) => String(s).replace(/[&<>"]/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[ch]);
new Function('w', 'S', '$', 'esc', 'follow', body + draw + '\ndrawFamilies(null);')(w, S, $, esc, null);
console.log(els.khd.textContent, '|', els.ksub.textContent);
const txt = els.ktree.innerHTML.replace(/<div class="hd">/g, '\n## ').replace(/<div class="kb">/g, '\n  ').replace(/<div class="kn"[^>]*>/g, '\n').replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/\n\s*\n/g, '\n');
console.log(txt.split('\n').slice(0, +(process.argv[4] || 40)).join('\n'));
console.log(`state roll ${(JSON.stringify(w.roll).length / 1024).toFixed(1)} KB`);
